import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const directory = new URL("assets/bridge-workshop/", root);
const assets = Object.fromEntries(readdirSync(directory).sort().map((name) => {
  const mediaType = name.endsWith(".webp") ? "image/webp" : "application/octet-stream";
  const bytes = readFileSync(new URL(name, directory));
  return [name, "data:" + mediaType + ";base64," + bytes.toString("base64")];
}));

const localInput = [
  'import { startBridge } from "./bridge-viewer.js";',
  "const assets = " + JSON.stringify(assets) + ";",
  'window.dispatchEvent(new CustomEvent("ice:bridge-local", { detail: { startBridge, assets } }));',
].join("\n");

function bundle(format, input) {
  const command = `esbuild --bundle --format=${format} --target=es2022 --minify --legal-comments=inline --sourcefile=bridge-entry.js`;
  const result = spawnSync(command, {
    cwd: fileURLToPath(root),
    shell: true,
    encoding: "utf8",
    input,
    maxBuffer: 8 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr || "esbuild could not bundle the bridge");
  return result.stdout;
}

const banner = "/* Generated by scripts/bundle-bridge-local.mjs. Three.js licence: three-LICENSE.txt. */\n";
const hosted = bundle("esm", 'export { startBridge } from "./bridge-viewer.js";');
const local = bundle("iife", localInput);
const hostedPath = "vendor/bridge-hosted.js";
const localPath = "vendor/bridge-local.js";
writeFileSync(new URL(hostedPath, root), banner + hosted);
writeFileSync(new URL(localPath, root), banner + local);

// A refreshed HTML document picks up new files even while the prior release is cached.
const entry = new URL("index.html", root);
const versioned = ["intro.js", "app.js", "style.css", "bridge-loading.js", `./${hostedPath}`, `./${localPath}`];
let html = readFileSync(entry, "utf8");
for (const path of versioned) {
  const version = createHash("sha256").update(readFileSync(new URL(path, root))).digest("hex").slice(0, 12);
  const reference = html.match(new RegExp(`"${path.replace(/[./]/g, "\\$&")}(?:\\?v=[a-f0-9]+)?"`));
  if (!reference) throw new Error(`Could not update ${path} in index.html`);
  html = html.replace(reference[0], `"${path}?v=${version}"`);
}
writeFileSync(entry, html);
